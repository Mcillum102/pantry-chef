export function localizeContent(value: string, language: AppLanguage) {
  return language === 'en' ? englishContent[value] ?? value : value;
}

export function formatAmount(amount: number | string, unit: string, language: AppLanguage) {
  return language === 'en'
    ? `${amount} ${localizeContent(unit, language)}`
    : `${amount}${localizeContent(unit, language)}`;
}
